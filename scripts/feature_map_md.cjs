'use strict';
const fs = require('fs'), path = require('path');
const {loadMap} = require('./feature_map_walk.cjs');
const output = path.resolve(__dirname,'../docs/feature-map.md');
function render(map) {
  const cell = value => String(value ?? '').replace(/\|/g,'\\|').replace(/\r?\n/g,' ');
  const lines = ['<!-- generated by scripts/feature_map_md.cjs from feature-map.json, do not edit by hand -->', '# 用户功能地图', '', '本文件由 JSON 确定性生成。范围为五个栏目、快捷筛选、阅读面板、精选清单及维护者入口。', '', '`stable` 仅表示选择器包含 id 或 data-* 属性，不保证内容永久不变。条件项按 setup 操作后验证；`skip` 是明确列出的离线限制。旧筛选行与旧侧栏被当前 CSS 隐藏，仅以 attached 状态记录。当前源码没有独立汉堡菜单；维护者模式通过 URL 开关提供机构链接。讨论提纲与综述速读在原容器内展开，并非独立对话框。', '', '操作词汇：`goto` = 站内相对地址；`click` = 点击首个匹配节点；`fill` = [选择器, 文本]；`wait` = 等待节点可见；`hover` = 悬停；`press` = [选择器, 按键]；`select` = [选择器, 选项值]。全部选择器使用标准 CSS。每个 setup 组从全新存储和栏目 URL 开始，组内共享操作结果。', '', '检查：`node scripts/feature_map_md.cjs --check`；遍历：`node scripts/feature_map_walk.cjs --viewport all`。遍历只访问本机临时服务器，远程请求全部中止；日期固定为离线构建时间，使用北京时间和浅色初始主题。', ''];
  for (const section of [...map.sections,{id:'global',title:'全局功能',...map.global}]) {
    lines.push(`## ${section.title}（${section.id}）`, '', '| id | 名称 | 选择器 | 类型 | 可见性/条件 | 稳定 |','| --- | --- | --- | --- | --- | --- |');
    for (const e of section.entries) lines.push(`| ${cell(e.id)} | ${cell(e.label)} | \`${cell(e.selector)}\` | ${e.kind} | ${cell(e.visible+' · '+e.viewports.join('/')+' · '+e.condition+(e.skip?' · SKIP: '+e.skip:''))} | ${e.stable?'是':'否'} |`);
    lines.push('', '| 状态 id | 状态 | 选择器 | 预期 | 操作 |', '| --- | --- | --- | --- | --- |');
    for (const s of section.states) lines.push(`| ${cell(s.id)} | ${cell(s.label)} | \`${cell(s.selector)}\` | ${cell(s.expect)} | ${cell(s.skip?'SKIP: '+s.skip:JSON.stringify(s.setup))} |`);
    lines.push('', '<details><summary>入口操作与备注</summary>', '');
    for (const e of section.entries) if (e.setup.length || e.notes) lines.push(`- **${e.id}**：\`${cell(JSON.stringify(e.setup))}\`${e.notes?'；'+cell(e.notes):''}`);
    lines.push('', '</details>', '');
  }
  return lines.join('\n');
}
module.exports={render};
if(require.main===module) {
 const text=render(loadMap());
 if(process.argv.includes('--check')) { if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==text){console.error('feature-map.md is stale: run node scripts/feature_map_md.cjs');process.exitCode=1;}else console.log('feature-map.md is current'); }
 else fs.writeFileSync(output,text);
}
